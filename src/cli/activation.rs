use anyhow::Context;
use std::path::Path;

pub(super) const NAME: &str = "activate";
pub(super) const DEACTIVATE_NAME: &str = "deactivate";

pub(super) const SAVE_ENVIRONMENT: &str = r#"if [ "${_APEXE_ACTIVE_SHIM_DIR+x}" != x ]; then
  _APEXE_PREVIOUS_PATH_SET="${PATH+x}"
  _APEXE_PREVIOUS_PATH="${PATH-}"
  _APEXE_PREVIOUS_SHIM_DIR_SET="${APEXE_SHIM_DIR+x}"
  _APEXE_PREVIOUS_SHIM_DIR="${APEXE_SHIM_DIR-}"
fi
"#;

const RESTORE_ENVIRONMENT: &str = r#"if [ "${_APEXE_ACTIVE_SHIM_DIR+x}" != x ]; then
  return 0
fi
if [ "$_APEXE_PREVIOUS_PATH_SET" = x ]; then
  export PATH="$_APEXE_PREVIOUS_PATH"
else
  unset PATH
fi
if [ "$_APEXE_PREVIOUS_SHIM_DIR_SET" = x ]; then
  export APEXE_SHIM_DIR="$_APEXE_PREVIOUS_SHIM_DIR"
else
  unset APEXE_SHIM_DIR
fi
unset _APEXE_ACTIVE_SHIM_DIR _APEXE_PREVIOUS_PATH_SET _APEXE_PREVIOUS_PATH
unset _APEXE_PREVIOUS_SHIM_DIR_SET _APEXE_PREVIOUS_SHIM_DIR
"#;

pub(super) fn generate(directory: &Path, executable: &Path) -> anyhow::Result<String> {
    let directory = quote_path(directory)?;
    let executable = quote_path(executable)?;
    Ok(format!(
        "# Generated by apexe. Source this file in sh, bash or zsh.\n\
         # Reload preserves installed settings and enables when no installation exists.\n\
         if ! {executable} env --reload --shim-dir {directory}; then return 1; fi\n\
         _APEXE_ACTIVATION_OUTPUT=\"$({executable} env --shim-dir {directory} --shell sh)\" || {{ unset _APEXE_ACTIVATION_OUTPUT; return 1; }}\n\
         if ! eval \"$_APEXE_ACTIVATION_OUTPUT\"; then unset _APEXE_ACTIVATION_OUTPUT; return 1; fi\n\
         unset _APEXE_ACTIVATION_OUTPUT\n"
    ))
}

pub(super) fn generate_deactivation(directory: &Path, executable: &Path) -> anyhow::Result<String> {
    let directory = quote_path(directory)?;
    let executable = quote_path(executable)?;
    Ok(format!(
        "# Generated by apexe. Source this file to disable shims and restore this shell.\n\
         if [ \"${{_APEXE_ACTIVE_SHIM_DIR+x}}\" = x ]; then\n\
           if [ \"$_APEXE_ACTIVE_SHIM_DIR\" != {directory} ]; then\n\
             printf '%s\\n' 'Another shim directory is active; source its deactivate script' >&2\n\
             return 1\n\
           fi\n\
           if [ \"${{_APEXE_PREVIOUS_PATH_SET+x}}${{_APEXE_PREVIOUS_PATH+x}}${{_APEXE_PREVIOUS_SHIM_DIR_SET+x}}${{_APEXE_PREVIOUS_SHIM_DIR+x}}\" != xxxx ]; then\n\
             printf '%s\\n' 'Saved activation environment is incomplete; refusing to disable' >&2\n\
             return 1\n\
           fi\n\
         fi\n\
         if ! {executable} env --disable --shim-dir {directory}; then return 1; fi\n\
         {RESTORE_ENVIRONMENT}"
    ))
}

fn quote_path(path: &Path) -> anyhow::Result<String> {
    let text = path
        .to_str()
        .ok_or_else(|| anyhow::anyhow!("Activation paths must be valid UTF-8"))?;
    anyhow::ensure!(
        path.is_absolute() && !text.contains(['\n', '\r']),
        "Activation paths must be absolute and must not contain line breaks"
    );
    Ok(shell_words::quote(text).into_owned())
}

pub(super) fn verify_existing(
    directory: &Path,
    name: &str,
    expected: Option<&str>,
) -> anyhow::Result<()> {
    let path = directory.join(name);
    match std::fs::symlink_metadata(&path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error).context("Cannot inspect activation script"),
        Ok(_) => {
            let expected = expected.ok_or_else(|| {
                anyhow::anyhow!(
                    "Refusing to overwrite unowned activation script {}",
                    path.display()
                )
            })?;
            require_owned(directory, name, expected)
        }
    }
}

pub(super) fn require_owned(directory: &Path, name: &str, expected: &str) -> anyhow::Result<()> {
    let path = directory.join(name);
    let metadata = std::fs::symlink_metadata(&path)
        .with_context(|| format!("Cannot inspect activation script {}", path.display()))?;
    anyhow::ensure!(
        metadata.file_type().is_file() && metadata.len() == expected.len() as u64,
        "Refusing to replace or remove changed activation script {}",
        path.display()
    );
    let content = std::fs::read_to_string(&path)
        .with_context(|| format!("Cannot read activation script {}", path.display()))?;
    anyhow::ensure!(content == expected,
        "Refusing to replace or remove modified activation script {}; restore its contents before retrying", path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_rejects_relative_and_line_break_paths() {
        let root = tempfile::tempdir().unwrap();
        let executable = root.path().join("apexe");
        for directory in [
            Path::new("relative").to_path_buf(),
            root.path().join("bad\npath"),
        ] {
            assert!(generate(&directory, &executable).is_err());
            assert!(generate_deactivation(&directory, &executable).is_err());
        }
        assert!(generate(root.path(), Path::new("relative-apexe")).is_err());
    }

    #[test]
    fn test_verify_existing_accepts_missing_script_but_check_requires_it() {
        let root = tempfile::tempdir().unwrap();
        verify_existing(root.path(), NAME, None).unwrap();
        assert!(require_owned(root.path(), NAME, "expected").is_err());
    }

    #[test]
    fn test_verify_existing_refuses_directory_and_changed_content() {
        let root = tempfile::tempdir().unwrap();
        std::fs::create_dir(root.path().join(NAME)).unwrap();
        assert!(verify_existing(root.path(), NAME, Some("expected")).is_err());
        std::fs::write(root.path().join(DEACTIVATE_NAME), "changed").unwrap();
        assert!(verify_existing(root.path(), DEACTIVATE_NAME, Some("expected")).is_err());
        assert!(verify_existing(root.path(), DEACTIVATE_NAME, None).is_err());
    }
}
